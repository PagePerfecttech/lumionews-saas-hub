import crypto from "crypto";

export interface ClientEnvInputs {
  // Publication Identity
  name: string;
  nameLocal?: string;
  shortName?: string;
  domain: string;
  siteUrl: string;

  // SaaS Hub Connection
  hubUrl: string;
  licenseKey: string;
  clientSecret: string;

  // Database
  databaseUrl?: string;
  directUrl?: string;

  // Cloudflare R2 Storage
  r2AccountId?: string;
  r2AccessKeyId?: string;
  r2SecretAccessKey?: string;
  r2BucketName?: string;
  r2PublicUrl?: string;

  // Branding
  primaryColor?: string;
  themeColor?: string;
  accentColor?: string;

  // Integrations (Optional)
  geminiApiKey?: string;
  googleAdsenseId?: string;
  onesignalAppId?: string;

  // Pre-existing secrets (if regenerating)
  authSecret?: string;
  kycEncryptionKey?: string;
  cronSecret?: string;
}

export interface GeneratedEnvResult {
  envContent: string;
  authSecret: string;
  kycEncryptionKey: string;
  cronSecret: string;
}

/**
 * Generates a complete, ready-to-paste production .env file template for Vercel deployment.
 * Automatically generates 32-byte cryptographically secure random secrets for auth, encryption, and cron.
 */
export function generateClientEnv(inputs: ClientEnvInputs): GeneratedEnvResult {
  const cleanSiteUrl = inputs.siteUrl.replace(/\/+$/, "");
  const cleanDomain = inputs.domain.replace(/^https?:\/\//i, "").replace(/\/.*$/, "").toLowerCase();
  const shortName =
    inputs.shortName ||
    inputs.name
      .split(/\s+/)
      .filter(Boolean)
      .map((w) => w[0])
      .join("")
      .slice(0, 4)
      .toUpperCase() ||
    "NEWS";

  const authSecret = inputs.authSecret || crypto.randomBytes(32).toString("hex");
  const kycEncryptionKey = inputs.kycEncryptionKey || crypto.randomBytes(32).toString("base64");
  const cronSecret = inputs.cronSecret || crypto.randomBytes(32).toString("hex");

  const primaryColor = inputs.primaryColor || "#C41E3A";
  const themeColor = inputs.themeColor || "#0F172A";
  const accentColor = inputs.accentColor || "#E11D48";

  const dbUrl = inputs.databaseUrl || "postgresql://user:password@ep-sample.ap-southeast-1.aws.neon.tech/news_db?sslmode=require";
  const r2AccId = inputs.r2AccountId || "";
  const r2KeyId = inputs.r2AccessKeyId || "";
  const r2Secret = inputs.r2SecretAccessKey || "";
  const r2Bucket = inputs.r2BucketName || `${cleanDomain.replace(/[^a-z0-9]/g, "-")}-media`;
  const r2Public = inputs.r2PublicUrl || `https://media.${cleanDomain}`;

  const defaultHubUrl = process.env.NEXT_PUBLIC_APP_URL || "https://app.smsinfotek.in";
  const hubUrl = (inputs.hubUrl && !inputs.hubUrl.includes("localhost") ? inputs.hubUrl : defaultHubUrl).replace(/\/+$/, "");

  const envContent = [
    `# ==============================================================================`,
    `# ${inputs.name.toUpperCase()} - PRODUCTION DEPLOYMENT ENVIRONMENT CONFIGURATION`,
    `# Generated by Lumio SaaS Master Control Plane on ${new Date().toISOString()}`,
    `# Central Hub: ${hubUrl}`,
    `# Paste these into Vercel Project -> Settings -> Environment Variables`,
    `# ==============================================================================`,
    ``,
    `# ------------------------------------------------------------------------------`,
    `# 1. CORE DATABASE & SECURITY (Required)`,
    `# ------------------------------------------------------------------------------`,
    `DATABASE_URL="${dbUrl}"`,
    inputs.directUrl ? `DIRECT_URL="${inputs.directUrl}"` : `# DIRECT_URL="${dbUrl}"`,
    `NEXTAUTH_SECRET="${authSecret}"`,
    `AUTH_SECRET="${authSecret}"`,
    `SITE_URL="${cleanSiteUrl}"`,
    `ADMIN_URL="${cleanSiteUrl}"`,
    `NEXTAUTH_URL="${cleanSiteUrl}"`,
    `KYC_ENCRYPTION_KEY="${kycEncryptionKey}"`,
    `CRON_SECRET="${cronSecret}"`,
    ``,
    `# ------------------------------------------------------------------------------`,
    `# 2. CENTRAL SAAS FLEET MANAGEMENT & REMOTE KILL-SWITCH (Required)`,
    `# ------------------------------------------------------------------------------`,
    `# Tied to license: ${inputs.licenseKey} | Domain: ${cleanDomain}`,
    `# To freeze or unlock this client, toggle in SaaS Hub at: ${hubUrl}`,
    `SAAS_HUB_URL="${hubUrl}"`,
    `SAAS_LICENSE_KEY="${inputs.licenseKey}"`,
    `SAAS_CLIENT_SECRET="${inputs.clientSecret}"`,
    ``,
    `# ------------------------------------------------------------------------------`,
    `# 3. WHITE-LABEL BRAND IDENTITY & LOCALIZATION`,
    `# ------------------------------------------------------------------------------`,
    `NEXT_PUBLIC_TENANT_NAME="${inputs.name}"`,
    `NEXT_PUBLIC_TENANT_SHORT_NAME="${shortName}"`,
    `NEXT_PUBLIC_TENANT_NAME_LOCAL="${inputs.nameLocal || inputs.name}"`,
    `NEXT_PUBLIC_TENANT_DOMAIN="${cleanDomain}"`,
    `NEXT_PUBLIC_SITE_URL="${cleanSiteUrl}"`,
    `NEXT_PUBLIC_PRIMARY_COLOR="${primaryColor}"`,
    `NEXT_PUBLIC_THEME_COLOR="${themeColor}"`,
    `NEXT_PUBLIC_ACCENT_COLOR="${accentColor}"`,
    `NEXT_PUBLIC_DEFAULT_LOCALE="te-IN"`,
    `NEXT_PUBLIC_LOCALE_REGION="IN"`,
    ``,
    `# ------------------------------------------------------------------------------`,
    `# 4. CLOUDFLARE R2 MEDIA STORAGE`,
    `# ------------------------------------------------------------------------------`,
    `R2_ACCOUNT_ID="${r2AccId}"`,
    `R2_ACCESS_KEY_ID="${r2KeyId}"`,
    `R2_SECRET_ACCESS_KEY="${r2Secret}"`,
    `R2_BUCKET_NAME="${r2Bucket}"`,
    `R2_PUBLIC_URL="${r2Public}"`,
    ``,
    `# ------------------------------------------------------------------------------`,
    `# 5. INTEGRATIONS & APIS (Optional)`,
    `# ------------------------------------------------------------------------------`,
    `GEMINI_API_KEY="${inputs.geminiApiKey || ""}"`,
    `GEMINI_MODEL="gemini-2.5-flash"`,
    `GOOGLE_ADSENSE_ID="${inputs.googleAdsenseId || ""}"`,
    `ONESIGNAL_APP_ID="${inputs.onesignalAppId || ""}"`,
    ``,
  ].join("\n");

  return {
    envContent,
    authSecret,
    kycEncryptionKey,
    cronSecret,
  };
}

